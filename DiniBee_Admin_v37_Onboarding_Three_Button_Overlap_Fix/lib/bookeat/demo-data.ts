  const pending = demoStore.restaurants.filter((item) => item.approvalStatus === "PENDING").length;
  const regular = demoStore.reservations.filter((item) => item.bookingType === "REGULAR").length;
  const group = demoStore.reservations.filter((item) => item.bookingType === "GROUP").length;
  const corporate = demoStore.reservations.filter((item) => item.bookingType === "CORPORATE").length;
  const checkedIn = demoStore.reservations.filter((item) => item.status === "CHECKED_IN").length;
  const dining = demoStore.reservations.filter((item) => item.status === "DINING").length;
  const occupiedTables = demoStore.reservations.filter((item) => item.tableStatus === "OCCUPIED").length;
  const onTheWay = demoStore.takeawayOrders.filter((item) => item.type === "ON_THE_WAY").length;
  const waitingTokens = demoStore.diniTickets.filter((item) => ["WAITING", "PREPARING", "READY", "CALLED"].includes(item.queueStatus)).length;
  const revenue = demoStore.payments.filter((item) => item.status === "PAID").reduce((sum, item) => sum + item.gatewayPaidAmount, 0);
  const commission = Math.round(revenue * 0.1);
  const pendingSettlements = demoStore.settlements.filter((item) => item.status !== "PAID").reduce((sum, item) => sum + item.netSettlement, 0);
  const customerOpen = demoStore.supportTickets.filter((item) => item.userType === "CUSTOMER" && ["OPEN", "IN_PROGRESS"].includes(item.status)).length;
  const ownerOpen = demoStore.supportTickets.filter((item) => item.userType === "OWNER" && ["OPEN", "IN_PROGRESS"].includes(item.status)).length;
  const issued = demoStore.walletTransactions.filter((item) => item.points > 0).reduce((sum, item) => sum + item.points, 0);
  const redeemed = Math.abs(demoStore.walletTransactions.filter((item) => item.type === "REDEEM").reduce((sum, item) => sum + item.points, 0));

